#!/usr/bin/env python3
"""Generate a Hsiao (72,64) SEC-DED parity-check matrix and emit SystemVerilog constants.

Columns for data bits: all 56 weight-3 columns plus 8 weight-5 columns chosen as the
cyclic rotations of 0b00011111, which keeps every row weight equal (26 data ones per row).
Check-bit columns are the 8 weight-1 columns (identity).
"""
from itertools import combinations

R, K = 8, 64
cols = []
for c in combinations(range(R), 3):
    cols.append(sum(1 << i for i in c))
base = 0b00011111
for s in range(8):
    cols.append(((base << s) | (base >> (8 - s))) & 0xFF)
assert len(cols) == K and len(set(cols)) == K
assert all(bin(c).count("1") % 2 == 1 for c in cols)
rows = [sum(((cols[j] >> i) & 1) << j for j in range(K)) for i in range(R)]
weights = [bin(r).count("1") for r in rows]
assert len(set(weights)) == 1, weights

def sv_concat(vals, width):
    # element 0 in the least-significant position
    return "{" + ", ".join(f"{width}'h{v:0{width//4}x}" for v in reversed(vals)) + "}"

print("  // Generated by scripts/gen_hsiao.py -- do not edit by hand.")
print(f"  // Row weight (data part) = {weights[0]} for every check bit.")
print("  // HSIAO_ROWS[i*64 +: 64] : data bits that feed check bit i.")
print(f"  localparam logic [8*64-1:0] HSIAO_ROWS =\n    {sv_concat(rows, 64)};")
print("  // HSIAO_COLS[j*8 +: 8]   : syndrome produced by an error in data bit j.")
print(f"  localparam logic [64*8-1:0] HSIAO_COLS =\n    {sv_concat(cols, 8)};")
